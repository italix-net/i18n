declare(strict_types=1);

namespace Italix\I18n;

use DateTimeInterface;
use DateTimeZone;

/**
 * The same answers as ICU, from tables ICU produced — no extension needed.
 *
 * Every number in {@see Baker} came out of ext-intl on a machine that had it.
 * This class looks them up; it does not have opinions of its own. That is the
 * difference between a fallback and a second implementation, and it is why the
 * differential suite can demand output **identical byte for byte** rather than
 * "close enough".
 *
 * ## It refuses more than it answers, on purpose
 *
 * Collation, spellout, display names and full MessageFormat are not here. Each
 * would have to be *approximated*, and an approximation that disagrees with the
 * reference only on the odd input is worse than an honest refusal: the same
 * catalogue would render differently depending on whether an extension happens
 * to be installed, and nobody would think to look for that.
 *
 * `supports()` says so in advance, and the methods throw with a reason.
 *
 * ## What it does answer
 *
 * Plural categories, numbers, currency, number parsing and dates — for the 24
 * official EU languages and nine regional forms. A locale outside that set is
 * refused rather than guessed at.
 */
final class PortableEngine implements Engine
{
    /** @var array<string, mixed>|null */
    private static $tables;

    /** @var array<string, string> */
    private const LETTER_CATEGORY = [
        'z' => 'zero', 'o' => 'one', 't' => 'two', 'f' => 'few', 'm' => 'many', 'x' => 'other',
    ];

    /** @var array<string, mixed> */
    private array $data;

    /** @param array<string, mixed>|null $tables for tests; production reads the baked file */
    public function __construct(?array $tables = null)
    {
        $this->data = $tables ?? self::tables();
    }

    /** @return array<string, mixed> */
    public static function tables(): array
    {
        if (self::$tables === null) {
            $path = __DIR__ . '/' . Baker::PATH;

            if (!is_file($path)) {
                throw new I18nException(
                    'The portable tables are missing: ' . $path . '. They are generated by '
                    . '`ix i18n:bake` on a machine with ext-intl, and committed.'
                );
            }

            self::$tables = (array) require $path;
        }

        return self::$tables;
    }

    public function name_code(): string
    {
        return 'portable';
    }

    public function supports(string $capability_c): bool
    {
        return in_array($capability_c, ['messages', 'numbers', 'dates', 'parsing'], true);
    }

    public function knows_locale(string $locale_c): bool
    {
        return $this->number_shape($locale_c) !== null;
    }

    // -------------------------------------------------------------------------
    // Plurals — the one thing a catalogue cannot do without
    // -------------------------------------------------------------------------

    public function plural_category_code(string $locale_c, $count): string
    {
        $language_c = self::language_of($locale_c);
        $shape_key  = $this->data['plural_locale'][$language_c] ?? null;

        if ($shape_key === null) {
            throw new I18nException(
                "No plural rules baked for \"{$locale_c}\". The portable engine carries the 24 "
                . 'official EU languages; run `ix i18n:bake` on a machine with ext-intl to add more.'
            );
        }

        $shape = $this->data['plural_shapes'][$shape_key];

        if (!is_int($count) && (float) $count !== floor((float) $count)) {
            $key_c = rtrim(rtrim(number_format((float) $count, 4, '.', ''), '0'), '.') ?: '0';

            if (isset($shape['decimals'][$key_c])) {
                return self::LETTER_CATEGORY[$shape['decimals'][$key_c]];
            }

            // A decimal outside the probed set. Every EU rule that treats
            // decimals specially does so uniformly, so the probe for 1.5 stands
            // in — and where a language has no decimal rule at all, that probe
            // *is* `other`, which is the right answer anyway.
            return self::LETTER_CATEGORY[$shape['decimals']['1.5'] ?? 'x'];
        }

        $n = abs((int) $count);

        // The tables hold 0–199 and the rules are periodic beyond that, which
        // Baker verifies over 4,800 values before writing a locale out.
        $index_n = $n <= 199 ? $n : 100 + ($n % 100);

        return self::LETTER_CATEGORY[$shape['integers'][$index_n]];
    }

    /**
     * A message with placeholders, and the plural/select forms a catalogue uses.
     *
     * **Not** a MessageFormat implementation, and the difference is the point.
     * ICU treats `'` as a quoting character, so `l'utente` means something
     * particular to it; a parser that handled apostrophes even slightly
     * differently would render the same catalogue two ways depending on which
     * engine ran — the worst failure available here. So anything beyond one
     * level of `plural` or `select`, or any use of `'`, is **refused**.
     *
     * @param array<string, mixed> $params
     */
    public function format_message(string $locale_c, string $message, array $params): string
    {
        if (strpos($message, '{') === false) {
            return $message;
        }

        if (strpos($message, "'") !== false) {
            throw new I18nException(
                'This message contains an apostrophe, which ICU reads as a quoting character. '
                . 'The portable engine will not guess at it: reword the message, or install ext-intl.'
            );
        }

        return $this->substitute($locale_c, $message, $params, 0);
    }

    /** @param array<string, mixed> $params */
    private function substitute(string $locale_c, string $message, array $params, int $depth_n): string
    {
        if ($depth_n > 1) {
            throw new I18nException(
                'Nested plural/select forms need ICU. The portable engine handles one level.'
            );
        }

        $out    = '';
        $length = strlen($message);

        for ($i = 0; $i < $length; $i++) {
            if ($message[$i] !== '{') {
                $out .= $message[$i];
                continue;
            }

            $end_n = self::matching_brace($message, $i);

            if ($end_n === null) {
                throw new I18nException('Unbalanced braces in a message.');
            }

            $inside_c = substr($message, $i + 1, $end_n - $i - 1);
            $out     .= $this->one_argument($locale_c, $inside_c, $params, $depth_n);
            $i        = $end_n;
        }

        return $out;
    }

    /** @param array<string, mixed> $params */
    private function one_argument(string $locale_c, string $inside_c, array $params, int $depth_n): string
    {
        $parts = explode(',', $inside_c, 3);
        $name_c = trim($parts[0]);

        if (count($parts) === 1) {
            return array_key_exists($name_c, $params) ? (string) $params[$name_c] : '{' . $name_c . '}';
        }

        $kind_c = trim($parts[1]);
        $body_c = $parts[2] ?? '';

        if ($kind_c !== 'plural' && $kind_c !== 'select') {
            throw new I18nException(
                "The portable engine handles `plural` and `select`; \"{$kind_c}\" needs ICU."
            );
        }

        $value = $params[$name_c] ?? null;

        $branches = self::branches($body_c);
        $wanted_c = $kind_c === 'select'
            ? (string) $value
            : $this->plural_category_code($locale_c, $value);

        // `=0` and `=1` win over the category, exactly as in ICU.
        $exact_c = '=' . (is_numeric($value) ? (string) (int) $value : '');

        $chosen_c = $branches[$exact_c] ?? $branches[$wanted_c] ?? $branches['other'] ?? null;

        if ($chosen_c === null) {
            throw new I18nException("No branch matched for \"{$name_c}\" and none was `other`.");
        }

        // `#` is the number itself, formatted for the locale.
        $chosen_c = $kind_c === 'plural'
            ? str_replace('#', $this->format_number($locale_c, (float) $value), $chosen_c)
            : $chosen_c;

        return $this->substitute($locale_c, $chosen_c, $params, $depth_n + 1);
    }

    /** @return array<string, string> */
    private static function branches(string $body_c): array
    {
        $out    = [];
        $length = strlen($body_c);
        $i      = 0;

        while ($i < $length) {
            while ($i < $length && ($body_c[$i] === ' ' || $body_c[$i] === "\n" || $body_c[$i] === "\t")) {
                $i++;
            }

            $start_n = $i;

            while ($i < $length && $body_c[$i] !== '{') {
                $i++;
            }

            if ($i >= $length) {
                break;
            }

            $key_c = trim(substr($body_c, $start_n, $i - $start_n));
            $end_n = self::matching_brace($body_c, $i);

            if ($end_n === null) {
                throw new I18nException('Unbalanced braces in a plural or select body.');
            }

            $out[$key_c] = substr($body_c, $i + 1, $end_n - $i - 1);
            $i           = $end_n + 1;
        }

        return $out;
    }

    private static function matching_brace(string $text, int $open_n): ?int
    {
        $depth_n = 0;
        $length  = strlen($text);

        for ($i = $open_n; $i < $length; $i++) {
            if ($text[$i] === '{') {
                $depth_n++;
            } elseif ($text[$i] === '}') {
                $depth_n--;

                if ($depth_n === 0) {
                    return $i;
                }
            }
        }

        return null;
    }

    // -------------------------------------------------------------------------
    // Numbers
    // -------------------------------------------------------------------------

    public function format_number(string $locale_c, float $value, array $options = []): string
    {
        $shape = $this->require_number_shape($locale_c);

        $decimals_n = $options['decimals'] ?? null;

        if ($decimals_n === null) {
            // ICU's default for DECIMAL is at most three fraction digits, and
            // it drops trailing zeros. Matching that is what makes 1234.5 come
            // out as "1.234,5" rather than "1.234,500".
            $rounded    = round($value, 3, PHP_ROUND_HALF_EVEN);
            $decimals_n = self::significant_decimals($rounded);
        } else {
            $rounded = round($value, (int) $decimals_n, PHP_ROUND_HALF_EVEN);
        }

        return self::assemble(
            $rounded,
            (int) $decimals_n,
            $shape['decimal_c'],
            ($options['grouping'] ?? true) ? $shape['group_c'] : '',
            (int) $shape['grouping_n'],
            $shape['minus_c']
        );
    }

    public function format_currency(string $locale_c, float $value, string $currency_c, array $options = []): string
    {
        $shape      = $this->require_number_shape($locale_c);
        $resolved_c = (string) $this->resolve_locale($locale_c);
        $currency_c = strtoupper(trim($currency_c));
        $decimals_n = $options['decimals'] ?? $this->currency_digits_n($currency_c);
        $rounded    = round($value, (int) $decimals_n, PHP_ROUND_HALF_EVEN);

        $key_c = $this->data['currency_affixes']['map'][$resolved_c][$currency_c] ?? null;
        $affix = $key_c === null ? null : $this->data['currency_affixes']['shapes'][$key_c];

        if ($affix === null) {
            throw new I18nException(
                "No currency table for {$currency_c} in \"{$locale_c}\". The portable engine "
                . 'carries ' . implode(', ', array_keys($this->data['currencies'])) . '.'
            );
        }

        $group_flag = (bool) ($this->data['currency_group'][$resolved_c] ?? true);

        $digits_c = self::assemble_digits(
            abs($rounded),
            (int) $decimals_n,
            $shape['currency_decimal_c'],
            $group_flag ? $shape['currency_group_c'] : '',
            (int) $shape['grouping_n']
        );

        // The affixes were taken whole from ICU's own rendering — including the
        // space CLDR inserts between an alphabetic symbol and a digit, which is
        // a rule with exceptions and therefore not one to reimplement.
        $side = $rounded < 0 ? $affix['negative'] : $affix['positive'];

        return $side['pre'] . $digits_c . $side['post'];
    }

    public function currency_digits_n(string $currency_c): int
    {
        $currency_c = strtoupper(trim($currency_c));

        if (!isset($this->data['currencies'][$currency_c])) {
            throw new I18nException(
                "No minor-unit table for \"{$currency_c}\". The portable engine carries "
                . implode(', ', array_keys($this->data['currencies'])) . '.'
            );
        }

        return (int) $this->data['currencies'][$currency_c]['digits_n'];
    }

    public function parse_number(string $locale_c, string $input): ?float
    {
        $shape = $this->require_number_shape($locale_c);

        $text = trim($input);

        if ($text === '') {
            return null;
        }

        $negative_flag = false;

        foreach ([$shape['minus_c'], '-'] as $minus_c) {
            if ($minus_c !== '' && strpos($text, $minus_c) === 0) {
                $negative_flag = true;
                $text          = substr($text, strlen($minus_c));
                break;
            }
        }

        $digits_c = str_replace($shape['group_c'], '', $text);
        $digits_c = str_replace($shape['decimal_c'], '.', $digits_c);

        // Trailing rubbish is a failure, not something to ignore: `(float)`
        // would read "12,5x" as 12.5 and nobody would learn that the x was
        // there.
        if (!preg_match('/^[0-9]+(\.[0-9]+)?$/', $digits_c)) {
            return null;
        }

        return $negative_flag ? -(float) $digits_c : (float) $digits_c;
    }

    // -------------------------------------------------------------------------
    // Dates
    // -------------------------------------------------------------------------

    public function format_date(string $locale_c, DateTimeInterface $when, string $style_c, string $timezone_c): string
    {
        $dates = $this->data['dates'][$this->resolve_locale($locale_c)] ?? null;

        if ($dates === null) {
            throw new I18nException("No date tables baked for \"{$locale_c}\".");
        }

        if (!isset($dates['patterns'][$style_c])) {
            throw new I18nException("Unknown date style \"{$style_c}\".");
        }

        $moment = (new \DateTimeImmutable('@' . $when->getTimestamp()))
            ->setTimezone(new DateTimeZone($timezone_c));

        return self::render_pattern($dates['patterns'][$style_c], $moment, $dates);
    }

    /**
     * A CLDR date pattern, applied.
     *
     * Only the fields the baked patterns actually use are implemented; anything
     * else throws rather than being dropped, because a date missing a field
     * looks like a date.
     *
     * @param array<string, mixed> $names
     */
    private static function render_pattern(string $pattern_c, \DateTimeImmutable $when, array $names): string
    {
        $out    = '';
        $length = strlen($pattern_c);
        $i      = 0;

        while ($i < $length) {
            $char_c = $pattern_c[$i];

            // Quoted literal: 'at' in "d MMMM y 'at' HH:mm".
            if ($char_c === "'") {
                $close_n = strpos($pattern_c, "'", $i + 1);

                if ($close_n === false) {
                    throw new I18nException('Unbalanced quote in a date pattern.');
                }

                $literal_c = substr($pattern_c, $i + 1, $close_n - $i - 1);
                $out      .= $literal_c === '' ? "'" : $literal_c;
                $i         = $close_n + 1;

                continue;
            }

            if (!ctype_alpha($char_c)) {
                $out .= $char_c;
                $i++;

                continue;
            }

            $run_n = 0;

            while ($i + $run_n < $length && $pattern_c[$i + $run_n] === $char_c) {
                $run_n++;
            }

            $out .= self::field($char_c, $run_n, $when, $names);
            $i   += $run_n;
        }

        return $out;
    }

    /** @param array<string, mixed> $names */
    private static function field(string $char_c, int $run_n, \DateTimeImmutable $when, array $names): string
    {
        $month_n = (int) $when->format('n');
        $iso_day = (int) $when->format('N');   // 1 = Monday, as the tables are built

        switch ($char_c) {
            case 'y':
                $year_c = $when->format('Y');

                return $run_n === 2 ? substr($year_c, -2) : $year_c;

            // `M` is the form used inside a date, `L` the standalone one. In
            // Polish, Czech and Greek those differ by grammatical case, and
            // using one for the other prints a date no native speaker writes.
            case 'M':
            case 'L':
                $long_c  = $char_c === 'L' ? 'months_alone' : 'months';
                $short_c = $char_c === 'L' ? 'months_alone_sh' : 'months_short';

                if ($run_n >= 4) {
                    return (string) $names[$long_c][$month_n - 1];
                }

                if ($run_n === 3) {
                    return (string) $names[$short_c][$month_n - 1];
                }

                return $run_n === 2 ? $when->format('m') : (string) $month_n;

            case 'd':
                return $run_n >= 2 ? $when->format('d') : $when->format('j');

            case 'E':
                return $run_n >= 4
                    ? (string) $names['days'][$iso_day - 1]
                    : (string) $names['days_short'][$iso_day - 1];

            case 'H':
                return $run_n >= 2 ? $when->format('H') : (string) (int) $when->format('G');

            case 'h':
                return $run_n >= 2 ? $when->format('h') : (string) (int) $when->format('g');

            case 'm':
                return $run_n >= 2 ? $when->format('i') : (string) (int) $when->format('i');

            case 's':
                return $run_n >= 2 ? $when->format('s') : (string) (int) $when->format('s');

            case 'a':
                return (int) $when->format('G') < 12
                    ? (string) $names['am_c']
                    : (string) $names['pm_c'];

            case 'G':
                return 'AD';
        }

        throw new I18nException(
            "The portable engine does not implement the date field \"{$char_c}\". "
            . 'Dropping it would produce something that still looks like a date.'
        );
    }

    // -------------------------------------------------------------------------
    // Shared plumbing
    // -------------------------------------------------------------------------

    /** @return array<string, mixed>|null */
    private function number_shape(string $locale_c): ?array
    {
        $resolved_c = $this->resolve_locale($locale_c);

        if ($resolved_c === null) {
            return null;
        }

        $key_c = $this->data['number_locale'][$resolved_c] ?? null;

        return $key_c === null ? null : $this->data['number_shapes'][$key_c];
    }

    /** @return array<string, mixed> */
    private function require_number_shape(string $locale_c): array
    {
        $shape = $this->number_shape($locale_c);

        if ($shape === null) {
            throw new I18nException(
                "No number tables baked for \"{$locale_c}\". The portable engine carries the 24 "
                . 'official EU languages and nine regional forms; `ix i18n:bake` adds more.'
            );
        }

        return $shape;
    }

    /** `it-CH` if it is baked, else `it`, else null. */
    private function resolve_locale(string $locale_c): ?string
    {
        $normalised_c = str_replace('_', '-', $locale_c);

        if (isset($this->data['number_locale'][$normalised_c])) {
            return $normalised_c;
        }

        $language_c = self::language_of($normalised_c);

        return isset($this->data['number_locale'][$language_c]) ? $language_c : null;
    }

    private static function language_of(string $locale_c): string
    {
        $parts = preg_split('/[-_]/', $locale_c);

        return strtolower($parts[0] ?? $locale_c);
    }

    /** How many decimals a rounded value actually needs, up to three. */
    private static function significant_decimals(float $value): int
    {
        for ($n = 0; $n < 3; $n++) {
            if (abs($value - round($value, $n)) < 1e-9) {
                return $n;
            }
        }

        return 3;
    }

    private static function assemble(
        float $value,
        int $decimals_n,
        string $decimal_c,
        string $group_c,
        int $grouping_n,
        string $minus_c
    ): string {
        $negative_flag = $value < 0;
        $out           = self::assemble_digits(abs($value), $decimals_n, $decimal_c, $group_c, $grouping_n);

        return $negative_flag ? $minus_c . $out : $out;
    }

    /**
     * The digits alone, grouped and pointed as the locale writes them.
     *
     * Public because {@see Baker} uses *this* function to find where the digits
     * sit inside ICU's own rendering. Two implementations of "assemble a
     * number" would defeat the purpose: the affixes must be cut with the same
     * knife they will later be glued back with.
     */
    public static function assemble_digits(
        float $value,
        int $decimals_n,
        string $decimal_c,
        string $group_c,
        int $grouping_n
    ): string {
        $text_c = number_format(abs($value), $decimals_n, '|', '');

        [$whole_c, $fraction_c] = array_pad(explode('|', $text_c), 2, '');

        if ($group_c !== '' && $grouping_n > 0 && strlen($whole_c) > $grouping_n) {
            $grouped_c = '';
            $count_n   = 0;

            for ($i = strlen($whole_c) - 1; $i >= 0; $i--) {
                if ($count_n > 0 && $count_n % $grouping_n === 0) {
                    $grouped_c = $group_c . $grouped_c;
                }

                $grouped_c = $whole_c[$i] . $grouped_c;
                $count_n++;
            }

            $whole_c = $grouped_c;
        }

        return $whole_c . ($decimals_n > 0 ? $decimal_c . $fraction_c : '');
    }

}
